// The access level every /api/v2 route needs: the one place that says who may call what. Read by
// accessRouter (src/web/middleware/access.js), which puts the matching guard in front of each route
// as it is registered. Keys are "METHOD /path" with the path as the route is mounted under /api/v2.
//
// Per-server levels (the server's access settings decide who has which, see access.js):
//   view   read-only: every page, list and setting of the server, nothing changed
//   inbox  view, plus acting on the inboxes: tickets, ban appeals, applications and suggestions
//   edit   everything: what Manage Server, Administrator and the bot-master roles always had
//
// Not tied to one server (the route keeps the guard it already has):
//   self      any signed-in person: their account, the server list, the release notes, the roadmap
//   operator  Sylo's operators (OWNER_IDS / FLUXER_OWNER_IDS): the route must carry requireOwner
//   member    a server's members (the web shop and the web application form), with their own check
//   public    no sign-in (/api/v2/public)
//
// A route that is not listed here needs edit, and test/v2.accessLevels.test.js fails until it is
// listed: a new route has to say which level it needs. A POST that only reads (insights refresh) may
// say view; a GET never needs more than view, except where a page shows a secret (GitHub webhook
// secrets are left out below edit, in the route itself).

